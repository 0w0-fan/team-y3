package org.springboot.demo.demos.web;

import org.springframework.stereotype.Controller;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseBody;

/**
 * @RequestMapping:请求映射->将访问的网络路径映射到该方法上
 * @ResponseBody：以Json形式响应数据
 * @RequestParam：设置请求参数的与形参的映射
 * @PathVariable：通过路径信息映射方法的形参
 *
 * @Controller：标记当前类的类型是控制层的类。控制层->与网络请求做对接，并调用服务层代码
 * @Service：服务层，将业务逻辑代码抽象到该层集中，方便代码的复用。
 * @Repository|@Mapper：持久层，衔接数据库，完成一系列数据库操作，仅保留操作数据库的代码。
 *
 * @Controller、@Service、@Repository、@Conponent 本质上完全一致，仅名称不同
 * @author <a href="mailto:chenxilzx1@gmail.com">theonefx</a>
 */
@Controller
public class BasicController {

    // http://127.0.0.1:8080/hello?name=lisi
    @RequestMapping("/hello")
    @ResponseBody
    public String hello(@RequestParam(name = "name", defaultValue = "unknown user") String name) {
        return "Hello " + name;
    }

    // http://127.0.0.1:8080/user
    @RequestMapping("/user")
    @ResponseBody
    public User user() {
        User user = new User();
        user.setName("theonefx");
        user.setAge(666);
        return user;
    }

    // http://127.0.0.1:8080/save_user?name=newName&age=11
    @RequestMapping("/save_user")
    @ResponseBody
    public String saveUser(User u) {
        return "user will save: name=" + u.getName() + ", age=" + u.getAge();
    }

    // http://127.0.0.1:8080/html
    @RequestMapping("/html")
    public String html(){
        return "index.html";
    }

    @ModelAttribute
    public void parseUser(@RequestParam(name = "name", defaultValue = "unknown user") String name
            , @RequestParam(name = "age", defaultValue = "12") Integer age, User user) {
        user.setName("zhangsan");
        user.setAge(18);
    }
}
